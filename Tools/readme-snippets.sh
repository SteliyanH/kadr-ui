#!/bin/sh
# Copies every ```swift block in README.md into Examples/ReadmeSnippets.swift,
# one function per block, so the KadrUIExamples target compiles the README.
#
#   Tools/readme-snippets.sh          regenerate the file
#   Tools/readme-snippets.sh --check  fail if the file is out of date (CI)
#
# A block that is not Swift you can compile (Package.swift, say) opts out with
# `<!-- readme-snippets: skip -->` on the line before its fence. Use it for
# that and nothing else: a fragment that needs context should get it, either
# in the README or as a placeholder value in Examples/ReadmeSnippetAssets.swift.
# (That file does not exist yet: every snippet today is a self-contained View
# that takes its `Video` as a property. Create it when a snippet needs one.)
#
# `<!-- readme-snippet: name -->` on the line before a fence names the block:
# its function is `readmeSnippet_name()` instead of a numbered one.
#
# Ported from kadr's Tools/readme-snippets.sh. The differences: the imports
# (SwiftUI and KadrUI), `@MainActor` on each function, and no GIF renderer.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
readme="$root/README.md"
out="$root/Examples/ReadmeSnippets.swift"

generate() {
    awk '
    BEGIN {
        print "// Generated by Tools/readme-snippets.sh from README.md. Do not edit:"
        print "// change the README and run the script again."
        print ""
        print "import CoreMedia"
        print "import Kadr"
        print "import KadrUI"
        print "import SwiftUI"
        n = 0; nlets = 0; nlines = 0; inblock = 0; skip = 0; prev = ""
    }
    !inblock && /^```swift[ \t]*$/ {
        inblock = 1
        skip = (prev ~ /<!-- readme-snippets: skip -->/)
        if (!skip) {
            n++
            name = n ""
            if (match(prev, /<!-- readme-snippet: [A-Za-z][A-Za-z0-9]* -->/)) {
                name = "_" substr(prev, RSTART + 21, RLENGTH - 25)
            }
            print ""
            printf "// README.md:%d\n", NR
            # Views and their initialisers are main-actor isolated, so a
            # fragment that builds one at the top level needs the main actor.
            printf "@MainActor\n"
            printf "func readmeSnippet%s() async throws {\n", name
        }
        next
    }
    inblock && /^```[ \t]*$/ {
        inblock = 0
        if (!skip) {
            # A snippet that ends on a top-level `let` it never reads would
            # warn. Using each top-level constant keeps the build warning-free.
            for (i = 1; i <= nlets; i++) printf "    _ = %s\n", lets[i]
            print "}"
        }
        nlets = 0; nlines = 0; prev = ""
        next
    }
    inblock {
        if (skip) next
        if ($0 ~ /^import /) next
        if (match($0, /^let [A-Za-z_][A-Za-z0-9_]*/)) lets[++nlets] = substr($0, 5, RLENGTH - 4)
        # Blank lines before the first code line (left by stripped imports)
        # are dropped, so the function body starts with code.
        if ($0 ~ /^[ \t]*$/) { if (nlines) print "" }
        else { print "    " $0; nlines++ }
        next
    }
    /[^ \t]/ { prev = $0 }
    END {
        if (inblock) { print "unterminated ```swift block in README.md" > "/dev/stderr"; exit 1 }
    }
    ' "$readme"
}

if [ "${1:-}" = "--check" ]; then
    if ! generate | diff -u "$out" - ; then
        echo "Examples/ReadmeSnippets.swift is out of date. Run Tools/readme-snippets.sh." >&2
        exit 1
    fi
else
    generate > "$out"
fi
